"""Generate frontend feature names from the initialized Python registry."""

import argparse
import json
import os
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from sentry.features.manager import FeatureManager

OUTPUT = Path("static/app/types/featureFlags.generated.ts")


def feature_flags_to_typescript(manager: "FeatureManager") -> str:
    # Registration imports require initialized Django settings.
    from sentry.features.base import OrganizationFeature, ProjectFeature
    from sentry.features.frontend import ClientFeature, OrganizationCapability, ProjectCapability

    registered = set(manager.all())
    if not registered:
        raise ValueError("The feature registry is empty; initialize Sentry before generating types")
    organization_features = {
        name.removeprefix("organizations:")
        for name in manager.all(OrganizationFeature, api_expose_only=True)
        if name.startswith("organizations:")
    } | set(OrganizationCapability)
    project_features = {
        name.removeprefix("projects:")
        for name in manager.all(ProjectFeature)
        if name.startswith("projects:")
    } | set(ProjectCapability)
    result = [
        "// Generated by `make build-feature-flag-types`.\n",
        "// Do not edit manually.\n\n",
        "import type {GetsentryOrganizationFeature, GetsentryProjectFeature} "
        "from './featureFlags.getsentry';\n\n",
    ]
    for type_name, names in (
        ("OrganizationFeature", organization_features),
        ("ProjectFeature", project_features),
        ("GlobalFeature", registered.intersection(ClientFeature)),
    ):
        members = [json.dumps(name) for name in sorted(names)]
        if type_name != "GlobalFeature":
            members.insert(0, f"Getsentry{type_name}")
        union = "\n  | ".join(members) or "never"
        result.append(f"export type {type_name} =\n  | {union};\n\n")
    result.append(
        "export type FeatureName =\n"
        "  | GlobalFeature\n"
        "  | OrganizationFeature\n"
        "  | ProjectFeature\n"
        "  | `organizations:${OrganizationFeature}`\n"
        "  | `projects:${ProjectFeature}`;\n"
    )
    return "".join(result)


def initialize_application() -> None:
    from sentry.runner import configure

    # Local dev configuration may import private registrations or override app loading.
    with NamedTemporaryFile(mode="w", suffix=".py") as config:
        config.write('SENTRY_CACHE = "sentry.cache.django.DjangoCache"\n')
        config.write(
            'from secrets import token_hex\nSENTRY_OPTIONS = {"system.secret-key": token_hex(32)}\n'
        )
        config.flush()
        os.environ["SENTRY_CONF"] = config.name
        configure(skip_service_validation=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    initialize_application()

    from sentry import features

    args.output.write_text(feature_flags_to_typescript(features.default_manager))


if __name__ == "__main__":
    main()
