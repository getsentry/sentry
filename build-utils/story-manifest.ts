import fs from 'node:fs';
import path from 'node:path';

import {createProcessor} from '@mdx-js/mdx';
import type {Compiler, RspackPluginInstance} from '@rspack/core';
import rspack from '@rspack/core';
import {parse as parseYaml} from 'yaml';

import {validateComponentCategory} from '../static/app/stories/componentCategories';

import {remarkPlugins} from './mdx-plugins.ts';
import {indexStoryHeadings} from './story-headings.ts';

const staticDir = path.resolve(import.meta.dirname, '../static');

/**
 * Directories scanned for stories. Manifest keys are paths relative to
 * `static/`, so each key starts with its root directory.
 *
 * The manifest is a module inside the `sentry` package, which does not depend
 * on `getsentry` or `admin`, so those roots are imported by relative path.
 */
const STORY_ROOTS = [
  {directory: 'app', importPrefix: 'sentry/'},
  {directory: 'gsApp', importPrefix: '../../gsApp/'},
  {directory: 'gsAdmin', importPrefix: '../../gsAdmin/'},
];

const PLUGIN_NAME = 'StoryManifestPlugin';
const STORY_GLOB = '**/*.{stories.tsx,mdx}';
const STORY_FILE_PATTERN = /(?:\.stories\.tsx|\.mdx)$/;
const WATCH_DEBOUNCE_MS = 25;

interface StoryFrontmatter {
  category?: string;
  figma?: string;
  keywords?: string[];
  title?: string;
}

function parseStoryFrontmatter(
  file: string,
  source: string
): StoryFrontmatter | undefined {
  const block = source.match(/^---\s*\n([\s\S]*?)\n---/)?.[1];
  const data = block && parseYaml(block);
  if (!data || typeof data !== 'object') {
    validateComponentCategory(file, undefined);
    return undefined;
  }

  validateComponentCategory(file, data.category);

  return {
    category: typeof data.category === 'string' ? data.category : undefined,
    figma:
      data.resources && typeof data.resources === 'object'
        ? data.resources.figma
        : undefined,
    keywords: Array.isArray(data.keywords)
      ? data.keywords.filter((keyword: unknown) => typeof keyword === 'string')
      : undefined,
    title: typeof data.title === 'string' ? data.title : undefined,
  };
}

// Parse with the MDX loader's plugins so the index sees the same tree that
// remarkStoryHeadings assigns IDs to during the build.
const mdxParser = createProcessor({remarkPlugins});

function toManifestKey(file: string) {
  return path.relative(staticDir, file).replaceAll('\\', '/');
}

function createManifest() {
  const stories = STORY_ROOTS.flatMap(({directory, importPrefix}) =>
    fs
      .globSync(STORY_GLOB, {cwd: path.join(staticDir, directory)})
      .map(file => file.replaceAll('\\', '/'))
      .map(file => ({
        file,
        key: `${directory}/${file}`,
        request: `${importPrefix}${file}`,
      }))
  ).sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

  const documents = stories
    .filter(({key}) => key.endsWith('.mdx'))
    .map(({file, key}) => {
      const source = fs.readFileSync(path.join(staticDir, key), 'utf8');
      return {
        key,
        // Component categories are validated against app-relative paths, so
        // only app stories can be core component docs.
        frontmatter: parseStoryFrontmatter(key.replace(/^app\//, ''), source),
        headings: indexStoryHeadings(mdxParser.parse({path: file, value: source})),
      };
    });
  const frontmatter = Object.fromEntries(
    documents.map(doc => [doc.key, doc.frontmatter])
  );
  const headings = Object.fromEntries(documents.map(doc => [doc.key, doc.headings]));

  const requests = stories.map(({request}) => request);
  const source = `// Generated by build-utils/story-manifest.ts. Do not edit.
// @ts-nocheck -- Rspack resolves explicit story extensions that TypeScript rejects.
export const storyImports: Record<string, () => Promise<unknown>> = {
${stories.map(({key, request}) => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(request)}),`).join('\n')}
};
export const storyFiles = Object.keys(storyImports);
export const storyFrontmatterIndex = ${JSON.stringify(frontmatter)};
export const storyHeadingIndex = ${JSON.stringify(headings)};
let hmrVersion = 0;
const hmrListeners = new Set<() => void>();
export const subscribeToStoriesHmr = (listener: () => void) => { hmrListeners.add(listener); return () => void hmrListeners.delete(listener); };
export const getStoriesHmrVersion = () => hmrVersion;
if (import.meta.webpackHot) {
  import.meta.webpackHot.accept([${requests.map(request => JSON.stringify(request)).join(',')}], () => { hmrVersion++; hmrListeners.forEach(listener => listener()); });
}
`;
  return {files: new Set(stories.map(({key}) => key)), source};
}

export class StoryManifestPlugin implements RspackPluginInstance {
  static readonly modulePath = 'app/stories/storyManifest.generated.ts';

  private manifest = createManifest();
  private pending = new Set<string>();
  private timer?: NodeJS.Timeout;
  // Seed the module here because writeModule() is only available after Rspack's
  // Rust compiler is initialized.
  // https://rspack.rs/plugins/rspack/virtual-modules-plugin#dynamic-module-creation
  private readonly virtualModules = new rspack.experiments.VirtualModulesPlugin({
    [StoryManifestPlugin.modulePath]: this.manifest.source,
  });
  private watchers: fs.FSWatcher[] = [];

  apply(compiler: Compiler) {
    this.virtualModules.apply(compiler);
    compiler.hooks.watchRun.tap(PLUGIN_NAME, () => {
      // rsbuild.config.ts excludes Story files from Rspack's watcher so the
      // manifest can update first. Debounce the duplicate events emitted by
      // editors that save by replacing a file.
      // https://rspack.rs/config/watch#watchoptionsignored
      if (this.watchers.length === 0) {
        this.watchers = STORY_ROOTS.map(({directory}) => {
          const rootDir = path.join(staticDir, directory);
          const watcher = fs.watch(rootDir, {recursive: true}, (_event, filename) => {
            if (filename && STORY_FILE_PATTERN.test(filename)) {
              this.pending.add(path.join(rootDir, filename));
              clearTimeout(this.timer);
              this.timer = setTimeout(() => {
                try {
                  this.flush(compiler);
                } catch (error) {
                  compiler
                    .getInfrastructureLogger(PLUGIN_NAME)
                    .error('Failed to update the Story manifest', error);
                }
              }, WATCH_DEBOUNCE_MS);
            }
          });
          watcher.on('error', error => {
            compiler
              .getInfrastructureLogger(PLUGIN_NAME)
              .error('Story manifest watcher failed', error);
            this.close();
          });
          return watcher;
        });
      }
    });
    compiler.hooks.watchClose.tap(PLUGIN_NAME, () => this.close());
    compiler.hooks.shutdown.tapPromise(PLUGIN_NAME, async () => this.close());
  }

  private flush(compiler: Compiler) {
    const changed = new Set([...this.pending].filter(file => fs.existsSync(file)));
    const removed = new Set([...this.pending].filter(file => !fs.existsSync(file)));
    const changedExistingStory = [...changed].some(file =>
      this.manifest.files.has(toManifestKey(file))
    );
    // Existing TS Stories cannot change the file list or MDX metadata, so avoid
    // rescanning every Story and reparsing every MDX file for that common case.
    const shouldRebuildManifest =
      removed.size > 0 ||
      [...changed].some(
        file => file.endsWith('.mdx') || !this.manifest.files.has(toManifestKey(file))
      );
    let manifestChanged = false;

    if (shouldRebuildManifest) {
      const next = createManifest();
      manifestChanged = next.source !== this.manifest.source;
      if (manifestChanged) {
        this.manifest = next;
        this.virtualModules.writeModule(StoryManifestPlugin.modulePath, next.source);
      }
    }
    if (!manifestChanged || changedExistingStory) {
      // Pass exact paths back to Rspack so incremental compilation can
      // distinguish modified modules from removals. This is the Rspack-specific
      // part of our custom watcher integration.
      // https://rspack.rs/api/javascript-api/compiler#watch
      compiler.watching?.invalidateWithChangesAndRemovals(changed, removed);
    }
    this.pending.clear();
  }

  private close() {
    clearTimeout(this.timer);
    for (const watcher of this.watchers) {
      watcher.close();
    }
    this.watchers = [];
  }
}
