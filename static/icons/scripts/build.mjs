/* eslint-env node */
/**
 * Generates src/sprite.generated.svg and src/names.generated.ts from the
 * raw SVG sources in src/. Run via `pnpm --filter @sentry/icons build`.
 */
import {promises as fs} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {loadConfig, optimize} from 'svgo';

const pkgRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const srcDir = path.join(pkgRoot, 'src');

const svgoConfig = await loadConfig(path.join(pkgRoot, 'svgo.config.mjs'));
if (!svgoConfig?.plugins) {
  throw new Error('Failed to load svgo.config.mjs');
}

const files = (await fs.readdir(srcDir)).filter(
  f => f.endsWith('.svg') && !f.endsWith('.generated.svg')
);
files.sort();

if (files.length === 0) {
  throw new Error(`No .svg sources found in ${srcDir}`);
}

/** @type {string[]} */
const symbols = [];
/** @type {Record<string, string>} */
const viewBoxes = {};

for (const file of files) {
  const name = path.basename(file, '.svg');
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`Icon file names must be kebab-case: ${file}`);
  }
  const raw = await fs.readFile(path.join(srcDir, file), 'utf8');
  const {data} = optimize(raw, {
    ...svgoConfig,
    path: file,
    // Namespace ids (clipPaths, gradients) so symbols cannot collide
    // once merged into a single sprite document.
    plugins: [...svgoConfig.plugins, {name: 'prefixIds', params: {prefix: name}}],
  });

  const match = data.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
  if (!match) {
    throw new Error(`Could not parse optimized SVG for ${file}`);
  }
  const [, attrs = '', content = ''] = match;
  const viewBox = attrs.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) {
    throw new Error(`Missing viewBox in ${file}`);
  }

  viewBoxes[name] = viewBox;
  symbols.push(`<symbol id="${name}" viewBox="${viewBox}">${content}</symbol>`);
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;

// Quote keys the way oxfmt would (only when not a valid identifier) so the
// generated file is formatter-stable.
/** @param {string} name */
const key = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

const viewBoxEntries = Object.entries(viewBoxes)
  .map(([name, viewBox]) => `  ${key(name)}: '${viewBox}',`)
  .join('\n');

const nameEntries = Object.keys(viewBoxes)
  .map(name => `  '${name}',`)
  .join('\n');

const names = `// Generated by scripts/build.mjs — do not edit.
export const ICON_VIEWBOXES = {
${viewBoxEntries}
} as const;

export type IconName = keyof typeof ICON_VIEWBOXES;

export const ICON_NAMES: IconName[] = [
${nameEntries}
];
`;

await fs.writeFile(path.join(srcDir, 'sprite.generated.svg'), sprite);
await fs.writeFile(path.join(srcDir, 'names.generated.ts'), names);

process.stdout.write(`Wrote ${files.length} icons to sprite.generated.svg\n`);
