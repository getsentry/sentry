/**
 * Generate one status-discriminated HTTP result wrapper for every SDK operation
 * that declares an error response in OpenAPI. Custom and non-HTTP errors reject.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { srcPath } from "../lib/generated-source.mjs";

export function emit({ normalizedSpec: spec }) {
  const sdkSource = readFileSync(srcPath("sdk.gen.ts"), "utf8");

  const errorRoutes = new Map();
  for (const [path, methods] of Object.entries(spec.paths ?? {})) {
    for (const [method, operation] of Object.entries(methods)) {
      if (typeof operation !== "object" || operation === null) continue;
      const statuses = Object.keys(operation.responses ?? {})
        .filter((status) => /^[45]\d\d$/.test(status))
        .map(Number)
        .sort((a, b) => a - b);
      if (statuses.length > 0) {
        errorRoutes.set(`${method.toUpperCase()} ${path}`, statuses);
      }
    }
  }

  const operations = [];
  for (const block of sdkSource.split(/^export const /m).slice(1)) {
    const functionMatch = block.match(/^(\w+) =/);
    const typeMatch = block.match(/Options<(\w+)Data,/);
    const urlMatch = block.match(/url: '([^']+)'/);
    const methodMatch = block.match(/\)\.(\w+)</);
    if (!functionMatch || !typeMatch || !urlMatch || !methodMatch) continue;

    const route = `${methodMatch[1].toUpperCase()} ${urlMatch[1]}`;
    const statuses = errorRoutes.get(route);
    if (!statuses) continue;

    operations.push({
      fn: functionMatch[1],
      optional: new RegExp(
        `^${functionMatch[1]} = <[^>]+>\\(options\\?:`,
      ).test(block),
      statuses,
      typeBase: typeMatch[1],
    });
  }
  operations.sort((a, b) => a.fn.localeCompare(b.fn));
  const typeNames = new Set();
  for (const { typeBase } of operations) {
    typeNames.add(`${typeBase}Data`);
    typeNames.add(`${typeBase}Errors`);
    typeNames.add(`${typeBase}Responses`);
  }

  const lines = [
    "// This file is auto-generated by scripts/generate-error-results.mjs",
    "// Do not edit directly. Re-run `pnpm build` to regenerate.",
    "",
    "import type { NarrowedResult } from './sentry-errors';",
    "import { callWithTypedErrors } from './sentry-errors';",
    "import type { Options } from './sdk.gen';",
    "import {",
    ...operations.map(({ fn }) => `    ${fn},`),
    "} from './sdk.gen';",
    "import type {",
    ...[...typeNames].sort().map((typeName) => `    ${typeName},`),
    "} from './types.gen';",
    "",
  ];

  for (const { fn, optional, statuses, typeBase } of operations) {
    const data = `${typeBase}Responses[keyof ${typeBase}Responses]`;
    const errors = `${typeBase}Errors`;
    lines.push(
      `/** Narrow default HTTP errors from \`${fn}\` by status. Custom and non-HTTP errors reject unchanged. */`,
      `export const narrowError_${fn} = async (`,
      `    options${optional ? "?" : ""}: Options<${typeBase}Data, false>,`,
      `): Promise<NarrowedResult<${data}, ${errors}>> =>`,
      `    callWithTypedErrors<${data}, ${errors}>(`,
      `        () => ${fn}({ ...options, responseStyle: 'fields', throwOnError: false }),`,
      `        [${statuses.join(", ")}],`,
      `    );`,
      "",
    );
  }

  writeFileSync(srcPath("error-results.gen.ts"), lines.join("\n"));
  console.log(
    `generate-error-results: ${operations.length} status-discriminated wrappers`,
  );
}
