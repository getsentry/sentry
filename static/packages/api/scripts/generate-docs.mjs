/** Generate the standalone API reference data from the same release inputs. */
import { copyFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { srcPath, writeSource } from "../lib/generated-source.mjs";
import { extractDocs } from "../lib/docs-catalog.mjs";

const f = ts.factory;

/** Attach `/** text *\/` to `node`. */
const documented = (node, text) =>
  ts.addSyntheticLeadingComment(node, ts.SyntaxKind.MultiLineCommentTrivia, `* ${text} `, true);

/** `export const name = docs.property;` */
const exportDocsProperty = (name, property, description) =>
  documented(
    f.createVariableStatement(
      [f.createModifier(ts.SyntaxKind.ExportKeyword)],
      f.createVariableDeclarationList(
        [f.createVariableDeclaration(name, undefined, undefined,
          f.createPropertyAccessExpression(f.createIdentifier("docs"), property))],
        ts.NodeFlags.Const,
      ),
    ),
    description,
  );

export function emit() {
  // build.mjs has made sourceSpec's paths relative already, and extractDocs
  // does that itself, so read the spec as Sentry publishes it.
  const spec = JSON.parse(readFileSync("./spec/openapi-derefed.json", "utf8"));
  for (const name of ["docs-types.ts", "docs-catalog.mjs", "api-base-path.mjs", "http-methods.mjs"]) {
    copyFileSync(fileURLToPath(new URL(`../lib/${name}`, import.meta.url)), srcPath(name));
  }
  const typesModule = f.createStringLiteral("./docs-types.ts");
  writeSource("docs.ts", [
    ts.addSyntheticLeadingComment(
      f.createImportDeclaration(
        undefined,
        f.createImportClause(true, undefined,
          f.createNamedImports([f.createImportSpecifier(false, undefined, f.createIdentifier("ApiDocs"))])),
        typesModule,
      ),
      ts.SyntaxKind.SingleLineCommentTrivia, " This file is auto-generated by scripts/generate-docs.mjs.", true,
    ),
    f.createExportDeclaration(undefined, true, undefined, typesModule),
    documented(
      f.createExportDeclaration(undefined, false,
        f.createNamedExports([f.createExportSpecifier(false, undefined, "extractDocs")]),
        f.createStringLiteral("./docs-catalog.mjs")),
      "Build the same data from another spec, such as a local build, to preview it.",
    ),
    // A JSON string literal parses faster than an object literal and keeps tsc
    // from inferring a type for megabytes of data.
    f.createVariableStatement(
      undefined,
      f.createVariableDeclarationList(
        [f.createVariableDeclaration("docs", undefined, f.createTypeReferenceNode("ApiDocs"),
          f.createCallExpression(
            f.createPropertyAccessExpression(f.createIdentifier("JSON"), "parse"),
            undefined,
            [f.createStringLiteral(JSON.stringify(extractDocs(spec)))],
          ))],
        ts.NodeFlags.Const,
      ),
    ),
    exportDocsProperty("API_BASE_PATH", "apiBasePath", "The path every operation path is relative to, from the spec's server URL."),
    exportDocsProperty("tags", "tags", "API reference categories, in specification order."),
    exportDocsProperty("operations", "operations", "API reference data for every operation, in specification order."),
  ]);
}
