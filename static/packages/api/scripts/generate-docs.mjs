/** Generate the standalone API reference data from the same release inputs. */
import { copyFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { srcPath } from "../lib/generated-source.mjs";
import { extractDocs } from "../lib/docs-catalog.mjs";

export function emit({ sourceSpec }) {
  for (const name of ["docs-types.ts", "docs-catalog.mjs", "http-methods.mjs"]) {
    copyFileSync(fileURLToPath(new URL(`../lib/${name}`, import.meta.url)), srcPath(name));
  }
  // A JSON string literal parses faster than an object literal and keeps tsc
  // from inferring a type for megabytes of data.
  writeFileSync(srcPath("docs.ts"), [
    "// This file is auto-generated by scripts/generate-docs.mjs.",
    "import type { ApiDocs } from './docs-types.ts';",
    "export type * from './docs-types.ts';",
    "/** Build the same data from another spec, such as a local build, to preview it. */",
    "export { extractDocs } from './docs-catalog.mjs';",
    "",
    `const docs: ApiDocs = JSON.parse(${JSON.stringify(JSON.stringify(extractDocs(sourceSpec)))});`,
    "",
    "/** API reference categories, in specification order. */",
    "export const tags = docs.tags;",
    "/** API reference data for every operation, in specification order. */",
    "export const operations = docs.operations;",
    "",
  ].join("\n"));
}
