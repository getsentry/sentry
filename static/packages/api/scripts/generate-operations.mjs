/** Generate the standalone, data-only operation catalog from the same release inputs. */
import { readFileSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { srcPath, writeSource } from "../lib/generated-source.mjs";
import { extractOperations } from "../lib/operation-catalog.mjs";

const f = ts.factory;

/** Attach `/** text *\/` to `node`. */
const documented = (node, text) =>
  ts.addSyntheticLeadingComment(node, ts.SyntaxKind.MultiLineCommentTrivia, `* ${text} `, true);

/** A JSON value as an expression: strings, numbers, booleans, null, arrays and objects. */
function literal(value) {
  if (value === null) return f.createNull();
  if (Array.isArray(value)) return f.createArrayLiteralExpression(value.map(literal), true);
  switch (typeof value) {
    case "string": return f.createStringLiteral(value);
    case "boolean": return value ? f.createTrue() : f.createFalse();
    case "number":
      return value < 0
        ? f.createPrefixUnaryExpression(ts.SyntaxKind.MinusToken, f.createNumericLiteral(-value))
        : f.createNumericLiteral(value);
    case "object":
      return f.createObjectLiteralExpression(
        Object.entries(value).map(([key, item]) => f.createPropertyAssignment(f.createStringLiteral(key), literal(item))),
        true,
      );
    default:
      throw new Error(`Unsupported catalog value: ${typeof value}`);
  }
}

const named = names => f.createNamedExports(names.map(name => f.createExportSpecifier(false, undefined, name)));

/** `export const name: type = initializer;` */
const exportConst = (name, type, initializer) =>
  f.createVariableStatement(
    [f.createModifier(ts.SyntaxKind.ExportKeyword)],
    f.createVariableDeclarationList([f.createVariableDeclaration(name, undefined, type, initializer)], ts.NodeFlags.Const),
  );

export function emit({ sourceSpec }) {
  const operations = extractOperations(sourceSpec, readFileSync(srcPath("sdk.gen.ts"), "utf8"));
  for (const name of ["operation-types.ts", "operation-match.ts"]) {
    copyFileSync(fileURLToPath(new URL(`../lib/${name}`, import.meta.url)), srcPath(name));
  }
  const types = f.createStringLiteral("./operation-types.ts");
  const match = f.createStringLiteral("./operation-match.ts");
  writeSource("operations.ts", [
    ts.addSyntheticLeadingComment(
      f.createImportDeclaration(
        undefined,
        f.createImportClause(true, undefined,
          f.createNamedImports([f.createImportSpecifier(false, undefined, f.createIdentifier("ApiOperation"))])),
        types,
      ),
      ts.SyntaxKind.SingleLineCommentTrivia, " This file is auto-generated by scripts/generate-operations.mjs.", true,
    ),
    f.createImportDeclaration(
      undefined,
      f.createImportClause(false, undefined, f.createNamedImports([
        f.createImportSpecifier(false, undefined, f.createIdentifier("createOperationMatcher")),
        f.createImportSpecifier(true, undefined, f.createIdentifier("ApiOperationMatcher")),
      ])),
      match,
    ),
    f.createExportDeclaration(undefined, true, named(["ApiOperation", "ApiOperationRouting", "ApiQueryParameter"]), types),
    f.createExportDeclaration(undefined, false, named(["API_BASE_PATH"]), f.createStringLiteral("./api-base-path.gen.ts")),
    f.createExportDeclaration(undefined, false, named(["createOperationMatcher"]), match),
    f.createExportDeclaration(undefined, true, named(["ApiOperationMatch", "ApiOperationMatcher", "ApiOperationTemplate"]), match),
    documented(
      exportConst("operations",
        f.createTypeOperatorNode(ts.SyntaxKind.ReadonlyKeyword,
          f.createArrayTypeNode(f.createTypeReferenceNode("ApiOperation"))),
        literal(operations)),
      "Offline metadata for the operations exported by this SDK version. Paths are relative to `API_BASE_PATH`.",
    ),
    documented(
      exportConst("matchOperation",
        f.createTypeReferenceNode("ApiOperationMatcher"),
        ts.addSyntheticLeadingComment(
          f.createCallExpression(f.createIdentifier("createOperationMatcher"), undefined, [f.createIdentifier("operations")]),
          ts.SyntaxKind.MultiLineCommentTrivia, " @__PURE__ ", false,
        )),
      "Find the catalog operation for a method and a concrete path, such as `matchOperation(\"GET\", \"/api/0/organizations/acme/issues/\")`; see `createOperationMatcher`.",
    ),
  ]);
}
