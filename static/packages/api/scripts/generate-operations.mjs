/** Generate the standalone, data-only operation catalog from the same release inputs. */
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { srcPath } from "../lib/generated-source.mjs";
import { extractOperations } from "../lib/operation-catalog.mjs";

export function emit({ sourceSpec }) {
  const operations = extractOperations(sourceSpec, readFileSync(srcPath("sdk.gen.ts"), "utf8"));
  copyFileSync(fileURLToPath(new URL("../lib/operation-types.ts", import.meta.url)), srcPath("operation-types.ts"));
  writeFileSync(srcPath("operations.ts"), [
    "// This file is auto-generated by scripts/generate-operations.mjs.",
    "import type { ApiOperation } from './operation-types.ts';",
    "export type { ApiOperation, ApiQueryParameter } from './operation-types.ts';",
    "export { API_BASE_PATH } from './api-base-path.gen.ts';",
    "",
    "/** Offline metadata for the operations exported by this SDK version. Paths are relative to `API_BASE_PATH`. */",
    `export const operations: readonly ApiOperation[] = ${JSON.stringify(operations, null, 2)};`,
    "",
  ].join("\n"));
}
