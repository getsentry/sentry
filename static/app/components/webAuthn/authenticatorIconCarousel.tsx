import {useEffect, useState} from 'react';
import {useTheme} from '@emotion/react';
import {AnimatePresence, motion, useReducedMotion} from 'framer-motion';

import {Container, Grid} from '@sentry/scraps/layout';

const ICON_ROTATION_INTERVAL_MS = 1800;
const AUTHENTICATOR_ICONS = [
  {name: 'touch-id', Icon: TouchIdIcon},
  {name: 'face-id', Icon: FaceIdIcon},
  {name: 'hardware-token', Icon: HardwareTokenIcon},
] as const;

interface AuthenticatorIconCarouselProps {
  isActive: boolean;
}

export function AuthenticatorIconCarousel({isActive}: AuthenticatorIconCarouselProps) {
  const theme = useTheme();
  const prefersReducedMotion = useReducedMotion();
  const [activeIconIndex, setActiveIconIndex] = useState(0);

  useEffect(() => {
    if (!isActive || prefersReducedMotion) {
      return;
    }

    const interval = window.setInterval(() => {
      setActiveIconIndex(index => (index + 1) % AUTHENTICATOR_ICONS.length);
    }, ICON_ROTATION_INTERVAL_MS);

    return () => window.clearInterval(interval);
  }, [isActive, prefersReducedMotion]);

  const {Icon, name} = AUTHENTICATOR_ICONS[activeIconIndex]!;

  return (
    <Grid aria-hidden="true" columns="48px" rows="48px" width="48px" height="48px">
      <AnimatePresence initial={false} mode="popLayout">
        <MotionContainer
          key={name}
          area="1 / 1"
          initial={{opacity: 0, scale: 0.95, x: -15}}
          animate={{opacity: 1, scale: 1, x: 0}}
          exit={{opacity: 0, scale: 0.95, x: 15}}
          transition={theme.motion.framer.smooth.slow}
        >
          <Icon />
        </MotionContainer>
      </AnimatePresence>
    </Grid>
  );
}

