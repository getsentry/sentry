import {useId, useMemo, useRef} from 'react';
import {ListKeyboardDelegate, useSelectableCollection} from '@react-aria/selection';
import {Item} from '@react-stately/collections';
import {useListState} from '@react-stately/list';
import {skipToken, useQuery} from '@tanstack/react-query';

import {NODE_ENV} from 'sentry/constants';

import type {ActiveTrigger} from './matching';
import type {AsyncComposerSource, ComposerSource} from './types';

interface SuggestionListItem {
  hideCheck: boolean;
  key: string;
  label: React.ReactNode;
  source: ComposerSource<unknown>;
  suggestion: unknown;
  textValue: string;
}

interface UseComposerSuggestionsOptions {
  activeSources: ReadonlyArray<ComposerSource<unknown>>;
  activeTrigger: ActiveTrigger | null;
  inputRef: React.RefObject<HTMLDivElement | null>;
}

const MAX_SUGGESTIONS = 50;

/**
 * Matches the option ID generated by React Aria's `useOption`. Its `getItemId`
 * helper cannot run until the child listbox has registered its state.
 */
function getOptionId(listBoxId: string, key: React.Key) {
  const normalizedKey = typeof key === 'string' ? key.replace(/\s*/g, '') : String(key);
  return `${listBoxId}-option-${normalizedKey}`;
}

function useSourceSuggestions(
  activeSources: ReadonlyArray<ComposerSource<unknown>>,
  query: string | undefined
) {
  // Multiple async sources per trigger group are not supported: hook count
  // must be stable across renders. Local sources can be arbitrarily many.
  if (NODE_ENV !== 'production') {
    const asyncCount = activeSources.filter(source => 'queryOptions' in source).length;
    if (asyncCount > 1) {
      throw new Error(
        `Composer supports at most one async source per trigger, found ${asyncCount}.`
      );
    }
  }
  const asyncSource = activeSources.find(
    (source): source is AsyncComposerSource<unknown> => 'queryOptions' in source
  );

  const suggestionsQuery = useQuery<readonly unknown[]>(
    asyncSource && query !== undefined
      ? asyncSource.queryOptions(query)
      : {queryKey: ['composer-suggestions'], queryFn: skipToken}
  );

  const suggestionsBySource = useMemo(() => {
    return activeSources.map(source => {
      if ('getSuggestions' in source) {
        return {
          source,
          suggestions: query === undefined ? [] : source.getSuggestions(query),
        };
      }
      return {source, suggestions: suggestionsQuery.data ?? []};
    });
  }, [activeSources, query, suggestionsQuery.data]);

  return {
    queryStatus: asyncSource ? suggestionsQuery.status : 'success',
    suggestionsBySource,
  };
}

export function useComposerSuggestions({
  activeSources,
  activeTrigger,
  inputRef,
}: UseComposerSuggestionsOptions) {
  const {queryStatus, suggestionsBySource} = useSourceSuggestions(
    activeSources,
    activeTrigger?.query
  );

  const items = useMemo(() => {
    return suggestionsBySource.flatMap(({source, suggestions}) =>
      suggestions.slice(0, MAX_SUGGESTIONS).map(suggestion => {
        const textValue = source.getText(suggestion);
        return {
          key: `${source.id}:${source.getId(suggestion)}`,
          hideCheck: true,
          label: source.renderSuggestion?.(suggestion) ?? textValue,
          source,
          suggestion,
          textValue,
        };
      })
    );
  }, [suggestionsBySource]);

  const listState = useListState<SuggestionListItem>({
    items,
    selectionMode: 'none',
    children: item => (
      <Item<SuggestionListItem> {...item} key={item.key}>
        {item.label}
      </Item>
    ),
  });

  const listBoxId = useId();
  const listBoxRef = useRef<HTMLUListElement>(null);
  const listBoxScrollRef = useRef<HTMLDivElement>(null);
  const focusedKey = listState.selectionManager.focusedKey;
  const activeDescendant =
    queryStatus === 'success' && items.length > 0 && focusedKey !== null
      ? getOptionId(listBoxId, focusedKey)
      : undefined;

  const keyboardDelegate = useMemo(
    () =>
      new ListKeyboardDelegate({
        collection: listState.collection,
        disabledKeys: listState.selectionManager.disabledKeys,
        ref: listBoxRef,
      }),
    [listBoxRef, listState.collection, listState.selectionManager.disabledKeys]
  );

  const {collectionProps} = useSelectableCollection({
    selectionManager: listState.selectionManager,
    keyboardDelegate,
    shouldFocusWrap: true,
    shouldUseVirtualFocus: true,
    disallowTypeAhead: true,
    ref: inputRef,
    scrollRef: listBoxScrollRef,
  });

  return {
    activeDescendant,
    collectionProps,
    focusedKey,
    getItem: (key: React.Key) => items.find(item => item.key === key),
    count: items.length,
    listBoxId,
    listBoxRef,
    listBoxScrollRef,
    listState,
    queryStatus,
  };
}
