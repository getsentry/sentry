import {useId, useMemo, useRef} from 'react';
import {ListKeyboardDelegate, useSelectableCollection} from '@react-aria/selection';
import {Item} from '@react-stately/collections';
import {useListState} from '@react-stately/list';
import {skipToken, useQuery} from '@tanstack/react-query';

import type {ActiveTrigger} from './matching';
import type {ComposerSource} from './types';

interface SuggestionListItem<T> {
  hideCheck: boolean;
  key: string;
  label: React.ReactNode;
  suggestion: T;
  textValue: string;
}

interface UseComposerSuggestionsOptions<T> {
  activeSource: ComposerSource<T> | undefined;
  activeTrigger: ActiveTrigger | null;
  inputRef: React.RefObject<HTMLDivElement | null>;
}

const MAX_SUGGESTIONS = 50;

/**
 * Matches the option ID generated by React Aria's `useOption`. Its `getItemId`
 * helper cannot run until the child listbox has registered its state.
 */
function getOptionId(listBoxId: string, key: React.Key) {
  const normalizedKey = typeof key === 'string' ? key.replace(/\s*/g, '') : String(key);
  return `${listBoxId}-option-${normalizedKey}`;
}

function useSourceSuggestions<T>(
  source: ComposerSource<T> | undefined,
  query: string | undefined
) {
  const queriedSource = source && 'queryOptions' in source ? source : undefined;
  const suggestionsQuery = useQuery(
    queriedSource && query !== undefined
      ? queriedSource.queryOptions(query)
      : {queryKey: ['composer-suggestions'], queryFn: skipToken}
  );
  const suggestions = useMemo(() => {
    if (!source || query === undefined) {
      return [];
    }

    if ('getSuggestions' in source) {
      return source.getSuggestions(query).slice(0, MAX_SUGGESTIONS);
    }

    const queriedSuggestions: readonly T[] | undefined = suggestionsQuery.data;
    return queriedSuggestions?.slice(0, MAX_SUGGESTIONS) ?? [];
  }, [query, source, suggestionsQuery.data]);

  return {
    queryStatus: queriedSource ? suggestionsQuery.status : 'success',
    suggestions,
  };
}

export function useComposerSuggestions<T>({
  activeTrigger,
  activeSource,
  inputRef,
}: UseComposerSuggestionsOptions<T>) {
  const {suggestions, queryStatus} = useSourceSuggestions(
    activeSource,
    activeTrigger?.query
  );

  const items = useMemo(() => {
    if (!activeSource) {
      return [];
    }

    return suggestions.map(suggestion => {
      const textValue =
        'getText' in activeSource
          ? activeSource.getText(suggestion)
          : activeSource.getId(suggestion);
      return {
        key: `${activeSource.id}:${activeSource.getId(suggestion)}`,
        hideCheck: true,
        label: activeSource.renderSuggestion?.(suggestion) ?? textValue,
        suggestion,
        textValue,
      };
    });
  }, [activeSource, suggestions]);

  const listState = useListState<SuggestionListItem<T>>({
    items,
    selectionMode: 'none',
    children: item => (
      <Item<SuggestionListItem<T>> {...item} key={item.key}>
        {item.label}
      </Item>
    ),
  });

  const listBoxId = useId();
  const listBoxRef = useRef<HTMLUListElement>(null);
  const listBoxScrollRef = useRef<HTMLDivElement>(null);
  const focusedKey = listState.selectionManager.focusedKey;
  const activeDescendant =
    queryStatus === 'success' && items.length > 0 && focusedKey !== null
      ? getOptionId(listBoxId, focusedKey)
      : undefined;

  const keyboardDelegate = useMemo(
    () =>
      new ListKeyboardDelegate({
        collection: listState.collection,
        disabledKeys: listState.selectionManager.disabledKeys,
        ref: listBoxRef,
      }),
    [listBoxRef, listState.collection, listState.selectionManager.disabledKeys]
  );

  const {collectionProps} = useSelectableCollection({
    selectionManager: listState.selectionManager,
    keyboardDelegate,
    shouldFocusWrap: true,
    shouldUseVirtualFocus: true,
    disallowTypeAhead: true,
    ref: inputRef,
    scrollRef: listBoxScrollRef,
  });

  return {
    activeDescendant,
    collectionProps,
    focusedKey,
    getSuggestion: (key: React.Key) => items.find(item => item.key === key)?.suggestion,
    count: items.length,
    listBoxId,
    listBoxRef,
    listBoxScrollRef,
    listState,
    queryStatus,
  };
}
