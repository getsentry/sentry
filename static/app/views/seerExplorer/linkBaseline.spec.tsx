/**
 * Every link Code Mode resolves today, pinned to the exact URL it produces — and, for inputs that
 * come close enough to matching a rule to be worth stating, that they resolve to no link at all.
 * Nothing else: row text is seer's, and how a row reads is settled in `callRecords.spec.tsx`.
 *
 * A characterization test, not a specification: these expectations were captured from the shipped
 * code, so a case here reading oddly means the app behaves oddly, and changing one is a product
 * decision rather than a test fix. It exists because the mapping is moving into a single rule table
 * (`links.tsx`) and nothing else covers the URLs the old `switch` emitted — port it wrong and this
 * fails loudly.
 *
 * The literals are written out rather than snapshotted so that a change to a destination shows up
 * as a reviewable diff and cannot be regenerated by `-u`.
 *
 * The adapters below are the only lines that follow the implementation. Point them at whatever
 * builds links now; the tables underneath do not move, except where a row is deliberately re-pinned
 * with a comment saying why.
 */
const organization = OrganizationFixture({slug: 'org-slug'});
