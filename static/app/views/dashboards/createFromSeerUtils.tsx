import * as Sentry from '@sentry/react';

import {validateDashboard} from 'sentry/actionCreators/dashboards';
import type {Organization} from 'sentry/types/organization';
import type {SeerExplorerResponse} from 'sentry/views/seerExplorer/types';

import {
  assignDefaultLayout,
  assignTempId,
  DEFAULT_WIDGET_WIDTH,
  getDefaultWidgetHeight,
  getInitialColumnDepths,
} from './layoutUtils';
import {DEFAULT_TABLE_LIMIT} from './types';
import type {DashboardDetails, Widget, WidgetLayout, WidgetQuery} from './types';

const DASHBOARD_ARTIFACT_KEY = 'dashboard';

type DashboardArtifact = {
  title: string;
  widgets: WidgetArtifact[];
};

type WidgetArtifact = {
  display_type: Widget['displayType'];
  interval: string;
  layout: {h: number; min_h: number; w: number; x: number; y: number};
  queries: Widget['queries'];
  title: string;
  widget_type: Widget['widgetType'];
  description?: string;
  limit?: number;
};

/**
 * Converts a Seer-generated widget artifact (snake_case) to a frontend Widget (camelCase).
 */
function normalizeWidgetCase(raw: WidgetArtifact): Widget {
  const {display_type, widget_type, ...rest} = raw;
  return {
    ...rest,
    displayType: display_type,
    widgetType: widget_type,
    layout: raw.layout
      ? {
          x: raw.layout.x,
          y: raw.layout.y,
          w: raw.layout.w,
          h: raw.layout.h,
          minH: raw.layout.min_h,
        }
      : undefined,
  };
}

/**
 * This function serves as a fallback to fill out any commonly missing or transform
 * any invalid attributes generated by Seer. For example, although attributes such
 * as limit and minH are specified as required by our schema, Seer does not always
 * generate them in practice. This function as a last step helps mitigate issues
 * where dashboards fail to save due to widgets falling into these scenarios.
 */
export function applySeerWidgetDefaults(widgets: Widget[]): Widget[] {
  return widgets.map(widget => {
    const layout = applyLayoutDefaults(widget.layout, widget.displayType);
    const limit = applyLimitDefaults(widget.limit);
    const queries = (widget.queries ?? []).map(applyQueryDefaults);

    return {
      ...widget,
      layout,
      limit,
      queries,
    };
  });
}

function applyQueryDefaults(query: WidgetQuery): WidgetQuery {
  return {
    ...query,
    aggregates: query.aggregates ?? [],
    columns: query.columns ?? [],
    fields: query.fields ?? [...(query.columns ?? []), ...(query.aggregates ?? [])],
    conditions: query.conditions ?? '',
    name: query.name ?? '',
    orderby: query.orderby ?? '',
  };
}

function applyLayoutDefaults(
  layout: WidgetLayout | null | undefined,
  displayType: Widget['displayType']
): WidgetLayout {
  const defaultMinH = getDefaultWidgetHeight(displayType);
  if (!layout) {
    return {
      w: DEFAULT_WIDGET_WIDTH,
      h: defaultMinH,
      x: 0,
      y: 0,
      minH: defaultMinH,
    };
  }
  return {
    ...layout,
    minH: layout.minH ?? defaultMinH,
  };
}

function applyLimitDefaults(limit: number | null | undefined): number {
  if (limit === null || limit === undefined) {
    return DEFAULT_TABLE_LIMIT;
  }
  return limit;
}

// The API returns query ids, but `WidgetQuery` doesn't declare them.
type WidgetQueryWithId = WidgetQuery & {id?: string | number};

function withoutId<T extends {id?: unknown}>({id: _id, ...rest}: T): Omit<T, 'id'> {
  return rest;
}

/**
 * Keeps the widget and query ids that Seer copied from the dashboard being
 * edited, so saving updates those rows instead of deleting and recreating
 * them. Any id that isn't on `currentWidgets` (invented, reused for a second
 * widget, or attached to another widget's query) is dropped, so that entry is
 * saved as new instead of failing the whole save.
 */
export function keepCurrentWidgetIds(
  widgets: Widget[],
  currentWidgets: Widget[]
): Widget[] {
  const currentQueryIds = new Map<string, Set<string>>();
  for (const widget of currentWidgets) {
    if (widget.id !== undefined) {
      currentQueryIds.set(
        String(widget.id),
        new Set(
          (widget.queries as WidgetQueryWithId[]).flatMap(query =>
            query.id === undefined ? [] : [String(query.id)]
          )
        )
      );
    }
  }

  // Ids are removed from these sets once used, so a copied id is kept only once.
  return widgets.map(widget => {
    const widgetId = widget.id === undefined ? undefined : String(widget.id);
    const queryIds = widgetId === undefined ? undefined : currentQueryIds.get(widgetId);
    if (widgetId === undefined || queryIds === undefined) {
      return {
        ...withoutId(widget),
        queries: (widget.queries as WidgetQueryWithId[]).map(withoutId),
      };
    }
    currentQueryIds.delete(widgetId);

    return {
      ...widget,
      id: widgetId,
      queries: (widget.queries as WidgetQueryWithId[]).map(query => {
        const queryId = query.id === undefined ? undefined : String(query.id);
        return queryId !== undefined && queryIds.delete(queryId)
          ? {...query, id: queryId}
          : withoutId(query);
      }),
    };
  });
}

/**
 * Extracts the latest dashboard artifact from a Seer Explorer session's blocks.
 * `currentWidgets` are the widgets of the dashboard being edited, if any.
 */
export function extractDashboardFromSession(
  session: NonNullable<SeerExplorerResponse['session']>,
  currentWidgets: Widget[] = []
): {
  title: string;
  widgets: Widget[];
} | null {
  for (const block of (session.blocks ?? []).toReversed()) {
    const artifact = block.artifacts?.find(
      a => a.key === DASHBOARD_ARTIFACT_KEY && a.data
    );
    if (artifact) {
      const data = artifact.data as DashboardArtifact;
      return {
        title: data.title,
        widgets: assignDefaultLayout(
          keepCurrentWidgetIds(
            applySeerWidgetDefaults(data.widgets.map(normalizeWidgetCase)),
            currentWidgets
          ).map(assignTempId),
          getInitialColumnDepths()
        ),
      };
    }
  }
  return null;
}

export function statusIsTerminal(status?: string | null) {
  return status === 'completed' || status === 'error' || status === 'awaiting_user_input';
}

/**
 * The dashboard generation endpoint prepends a block of system instructions to
 * the user's prompt before sending it to Seer, terminated by this marker (see
 * `DASHBOARD_INSTRUCTIONS` in `organization_dashboard_generate.py`). Splitting on
 * it lets the chat UI show only what the user actually typed and tuck the
 * instructions behind a collapsible disclosure instead of leaking them inline.
 */
const DASHBOARD_INSTRUCTIONS_MARKER = 'User Query:\n';

export function splitDashboardPrompt(content: string): {
  instructions: string | null;
  query: string;
} {
  const markerIndex = content.indexOf(DASHBOARD_INSTRUCTIONS_MARKER);
  if (markerIndex === -1) {
    return {instructions: null, query: content};
  }
  const instructions = content.slice(0, markerIndex).trim();
  const query = content.slice(markerIndex + DASHBOARD_INSTRUCTIONS_MARKER.length).trim();
  return {instructions: instructions || null, query};
}

export async function validateDashboardAndRecordMetrics({
  organization,
  dashboard,
  seerRunId,
  source,
}: {
  dashboard: DashboardDetails;
  organization: Organization;
  seerRunId: number | null;
  source: 'create' | 'edit';
}) {
  try {
    await validateDashboard(organization.slug, dashboard);
    Sentry.metrics.count('dashboards.seer.validation', 1, {
      attributes: {
        status: 'success',
        organization_slug: organization.slug,
        ...(seerRunId ? {seer_run_id: seerRunId} : {}),
        source,
      },
    });
  } catch (error) {
    Sentry.metrics.count('dashboards.seer.validation', 1, {
      attributes: {
        status: 'failure',
        organization_slug: organization.slug,
        ...(seerRunId ? {seer_run_id: seerRunId} : {}),
        source,
      },
    });
    Sentry.captureException(error, {
      tags: {seer_run_id: seerRunId},
    });
  }
}
