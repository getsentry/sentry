const DASHBOARD_ARTIFACT_KEY = 'dashboard';

type DashboardArtifact = {
  title: string;
  widgets: WidgetArtifact[];
  environment?: string[];
  projects?: number[];
};

export type GeneratedDashboard = {
  environment: string[];
  projects: number[];
  title: string;
  widgets: Widget[];
};

type WidgetArtifact = {
  display_type: Widget['displayType'];
  interval: string;
  layout: {h: number; min_h: number; w: number; x: number; y: number};
  queries: Widget['queries'];
  title: string;
  widget_type: Widget['widgetType'];
  description?: string;
  limit?: number;
};

/**
 * Converts a Seer-generated widget artifact (snake_case) to a frontend Widget (camelCase).
 */
function normalizeWidgetCase(raw: WidgetArtifact): Widget {
  const {display_type, widget_type, ...rest} = raw;
  return {
    ...rest,
    displayType: display_type,
    widgetType: widget_type,
    layout: raw.layout
      ? {
          x: raw.layout.x,
          y: raw.layout.y,
          w: raw.layout.w,
          h: raw.layout.h,
          minH: raw.layout.min_h,
        }
      : undefined,
  };
}

/**
 * This function serves as a fallback to fill out any commonly missing or transform
 * any invalid attributes generated by Seer. For example, although attributes such
 * as limit and minH are specified as required by our schema, Seer does not always
 * generate them in practice. This function as a last step helps mitigate issues
 * where dashboards fail to save due to widgets falling into these scenarios.
 */
export function applySeerWidgetDefaults(widgets: Widget[]): Widget[] {
  return widgets.map(widget => {
    const layout = applyLayoutDefaults(widget.layout, widget.displayType);
    const limit = applyLimitDefaults(widget.limit);

    return {
      ...widget,
      layout,
      limit,
    };
  });
}

function applyLayoutDefaults(
  layout: WidgetLayout | null | undefined,
  displayType: Widget['displayType']
): WidgetLayout {
  const defaultMinH = getDefaultWidgetHeight(displayType);
  if (!layout) {
    return {
      w: DEFAULT_WIDGET_WIDTH,
      h: defaultMinH,
      x: 0,
      y: 0,
      minH: defaultMinH,
    };
  }
  return {
    ...layout,
    minH: layout.minH ?? defaultMinH,
  };
}

function applyLimitDefaults(limit: number | null | undefined): number {
  if (limit === null || limit === undefined) {
    return DEFAULT_TABLE_LIMIT;
  }
  return limit;
}

/**
 * Extracts the latest dashboard artifact from a Seer Explorer session's blocks.
 */
export function extractDashboardFromSession(
  session: NonNullable<SeerExplorerResponse['session']>
): GeneratedDashboard | null {
  for (const block of (session.blocks ?? []).toReversed()) {
    const artifact = block.artifacts?.find(
      a => a.key === DASHBOARD_ARTIFACT_KEY && a.data
    );
    if (artifact) {
      const data = artifact.data as DashboardArtifact;
      return {
        title: data.title,
        projects: data.projects ?? [],
        environment: data.environment ?? [],
        widgets: assignDefaultLayout(
          applySeerWidgetDefaults(data.widgets.map(normalizeWidgetCase)).map(
            assignTempId
          ),
          getInitialColumnDepths()
        ),
      };
    }
  }
  return null;
}

const PROJECT_SLUG_FILTER_KEYS = new Set(['project', 'project.name']);

/**
 * Collects project slugs that generated widget queries require via positive
 * `project:` / `project.name:` filters. The events APIs reject these filters
 * with a 400 when the slug isn't part of the request's project selection, so
 * the preview must select these projects for the widgets to load.
 *
 * Negated and wildcard filters are skipped because the API doesn't require
 * those projects to be selected.
 */
export function getProjectSlugsFromWidgets(widgets: Widget[]): string[] {
  const slugs = new Set<string>();

  for (const widget of widgets) {
    for (const query of widget.queries ?? []) {
      const parsed = parseSearch(query.conditions ?? '', {flattenParenGroups: true});

      for (const token of parsed ?? []) {
        if (
          token.type !== Token.FILTER ||
          token.negated ||
          (token.operator !== TermOperator.DEFAULT &&
            token.operator !== TermOperator.EQUAL) ||
          !PROJECT_SLUG_FILTER_KEYS.has(getKeyName(token.key))
        ) {
          continue;
        }

        const values =
          token.value.type === Token.VALUE_TEXT_LIST
            ? token.value.items.map(item => item.value?.value)
            : token.value.type === Token.VALUE_TEXT
              ? [token.value.value]
              : [];

        for (const value of values) {
          if (value && !value.includes('*')) {
            slugs.add(value);
          }
        }
      }
    }
  }

  return [...slugs];
}

export type GeneratedDashboardPageFilters = {
  environment?: string[];
  project?: string[];
};

/**
 * Determines the page filter query params the preview needs so that a
 * generated dashboard's widgets can query the projects they reference.
 *
 * Returns null when the current URL selection already covers the dashboard.
 * Selections are only ever widened, so a user's explicit selection is kept.
 */
export function getGeneratedDashboardPageFilters({
  dashboard,
  query,
  projects,
}: {
  dashboard: Pick<GeneratedDashboard, 'environment' | 'projects' | 'widgets'>;
  projects: Project[];
  query: Location['query'];
}): GeneratedDashboardPageFilters | null {
  const update: GeneratedDashboardPageFilters = {};

  const selectedProjectIds = decodeList(query.project)
    .map(Number)
    .filter(id => !Number.isNaN(id));
  const hasAllProjects = selectedProjectIds.includes(ALL_ACCESS_PROJECTS);

  if (!hasAllProjects) {
    const slugToId = new Map(projects.map(project => [project.slug, Number(project.id)]));
    const requiredIds = [
      ...dashboard.projects,
      ...getProjectSlugsFromWidgets(dashboard.widgets).flatMap(slug => {
        const id = slugToId.get(slug);
        return id === undefined ? [] : [id];
      }),
    ];

    // An empty selection means "My Projects". Unless Seer scoped the dashboard
    // itself, keep those selected so widgets without a project filter keep
    // showing the same data.
    const baseIds =
      selectedProjectIds.length > 0
        ? selectedProjectIds
        : dashboard.projects.length > 0
          ? []
          : projects
              .filter(project => project.isMember)
              .map(project => Number(project.id));

    const baseIdSet = new Set(baseIds);
    const missingIds = [...new Set(requiredIds)].filter(id => !baseIdSet.has(id));

    if (missingIds.length > 0) {
      update.project = [...baseIds, ...missingIds].map(String);
    }
  }

  if (dashboard.environment.length > 0 && decodeList(query.environment).length === 0) {
    update.environment = dashboard.environment;
  }

  return update.project || update.environment ? update : null;
}

/**
 * Whether the URL query already reflects the given page filter update.
 */
export function queryHasPageFilters(
  query: Location['query'],
  pageFilters: GeneratedDashboardPageFilters
): boolean {
  const matches = (key: keyof GeneratedDashboardPageFilters) => {
    const expected = pageFilters[key];
    if (!expected) {
      return true;
    }
    const actual = new Set(decodeList(query[key]));
    return actual.size === expected.length && expected.every(value => actual.has(value));
  };
  return matches('project') && matches('environment');
}

export function statusIsTerminal(status?: string | null) {
  return status === 'completed' || status === 'error' || status === 'awaiting_user_input';
}

/**
 * The dashboard generation endpoint prepends a block of system instructions to
 * the user's prompt before sending it to Seer, terminated by this marker (see
 * `DASHBOARD_INSTRUCTIONS` in `organization_dashboard_generate.py`). Splitting on
 * it lets the chat UI show only what the user actually typed and tuck the
 * instructions behind a collapsible disclosure instead of leaking them inline.
 */
const DASHBOARD_INSTRUCTIONS_MARKER = 'User Query:\n';

export function splitDashboardPrompt(content: string): {
  instructions: string | null;
  query: string;
} {
  const markerIndex = content.indexOf(DASHBOARD_INSTRUCTIONS_MARKER);
  if (markerIndex === -1) {
    return {instructions: null, query: content};
  }
  const instructions = content.slice(0, markerIndex).trim();
  const query = content.slice(markerIndex + DASHBOARD_INSTRUCTIONS_MARKER.length).trim();
  return {instructions: instructions || null, query};
}

export async function validateDashboardAndRecordMetrics({
  organization,
  dashboard,
  seerRunId,
  source,
}: {
  dashboard: DashboardDetails;
  organization: Organization;
  seerRunId: number | null;
  source: 'create' | 'edit';
}) {
  try {
    await validateDashboard(organization.slug, dashboard);
    Sentry.metrics.count('dashboards.seer.validation', 1, {
      attributes: {
        status: 'success',
        organization_slug: organization.slug,
        ...(seerRunId ? {seer_run_id: seerRunId} : {}),
        source,
      },
    });
  } catch (error) {
    Sentry.metrics.count('dashboards.seer.validation', 1, {
      attributes: {
        status: 'failure',
        organization_slug: organization.slug,
        ...(seerRunId ? {seer_run_id: seerRunId} : {}),
        source,
      },
    });
    Sentry.captureException(error, {
      tags: {seer_run_id: seerRunId},
    });
  }
}
