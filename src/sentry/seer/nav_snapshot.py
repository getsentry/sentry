"""Sentry's UI navigation pages, filtered per org for Seer's nav links.

Conditions are JSON: `{"flag": name}`, `{"org": attribute}`, `{"deployment": kind}`,
`{"scope": permission}`, `{"unknown": source_expression}`, combined with `{"all": [...]}`,
`{"any": [...]}` and `{"not": cond}`. A missing condition means always shown.
"""

from __future__ import annotations

from collections.abc import Collection
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from sentry.utils import json
from sentry.utils.settings import is_self_hosted, is_self_hosted_errors_only

Condition = dict[str, Any]

CRUMB_SEPARATOR = " → "
_SETTINGS_SECTION_ALIASES = frozenset({"settings", "account", "organization", "projects"})

# Generated by `python -m tools.seer_nav.generate_snapshot` from the frontend nav source.
# Do not edit nav_snapshot.generated.json by hand.
_SNAPSHOT: dict[str, Any] = json.loads(
    (Path(__file__).parent / "nav_snapshot.generated.json").read_text()
)


def get_nav_snapshot() -> dict[str, Any]:
    """Return the Sentry pages Seer can link to, as `{"version": int, "entries": [...]}`."""
    return _SNAPSHOT


@dataclass(frozen=True)
class VisibleNavLink:
    crumbs: str
    path: str
    # The part of the page's condition that couldn't be decided, or None if always shown.
    pending: Condition | None


@dataclass(frozen=True)
class NavSummary:
    # Section to its labels, the section header first.
    sections: dict[str, list[str]]
    prebuilt_dashboards: list[str]
    explore_tabs: list[str]
    # Each flag the nav files reference, and whether the org has it.
    flags: dict[str, bool]


def nav_summary(features: Collection[str]) -> NavSummary:
    """The nav summary, with the flags it references evaluated against the org's `features`."""
    summary = _SNAPSHOT["summary"]
    features = frozenset(features)
    return NavSummary(
        sections=summary["sections"],
        prebuilt_dashboards=summary["prebuilt_dashboards"],
        explore_tabs=summary["explore_tabs"],
        flags={flag: flag in features for flag in summary["flags"]},
    )


def _deployment(kind: str) -> bool | None:
    if kind == "self_hosted":
        return is_self_hosted()
    if kind == "self_hosted_errors_only":
        return is_self_hosted_errors_only()
    return None


def resolve_condition(
    cond: Condition | None, features: Collection[str], scopes: Collection[str]
) -> bool | Condition:
    """True/False when the org's `features` and the user's `scopes` decide the condition,
    otherwise the still-undecided part."""
    if cond is None:
        return True
    if "all" in cond:
        parts = [resolve_condition(c, features, scopes) for c in cond["all"]]
        if any(p is False for p in parts):
            return False
        rest: list[bool | Condition] = [p for p in parts if p is not True]
        return True if not rest else rest[0] if len(rest) == 1 else {"all": rest}
    if "any" in cond:
        parts = [resolve_condition(c, features, scopes) for c in cond["any"]]
        if any(p is True for p in parts):
            return True
        rest = [p for p in parts if p is not False]
        return False if not rest else rest[0] if len(rest) == 1 else {"any": rest}
    if "not" in cond:
        inner = resolve_condition(cond["not"], features, scopes)
        return (not inner) if isinstance(inner, bool) else {"not": inner}
    if "flag" in cond:
        return cond["flag"] in features
    if "scope" in cond:
        return cond["scope"] in scopes
    if "deployment" in cond:
        deployed = _deployment(cond["deployment"])
        return cond if deployed is None else deployed
    return cond


def _has_unknown(cond: Condition) -> bool:
    if "unknown" in cond:
        return True
    children = cond.get("all") or cond.get("any") or ([cond["not"]] if "not" in cond else [])
    return any(_has_unknown(c) for c in children)


def _without_unknowns(cond: Condition) -> Condition | None:
    """The undecided condition with unreadable source dropped, or None if it can't be.

    An `any` keeps its readable alternatives: dropping an alternative only makes the
    condition stricter, so the page is never offered more widely than the frontend shows it.
    """
    if "any" in cond:
        kept = [c for c in (_without_unknowns(c) for c in cond["any"]) if c is not None]
        return None if not kept else kept[0] if len(kept) == 1 else {"any": kept}
    if "all" in cond:
        parts = [_without_unknowns(c) for c in cond["all"]]
        return None if any(p is None for p in parts) else {"all": parts}
    # Under a `not`, dropping an alternative would loosen the condition instead.
    return None if _has_unknown(cond) else cond


def describe_condition(cond: Condition) -> str:
    if "all" in cond:
        return " and ".join(describe_condition(c) for c in cond["all"])
    if "any" in cond:
        return "(" + " or ".join(describe_condition(c) for c in cond["any"]) + ")"
    if "not" in cond:
        return f"not {describe_condition(cond['not'])}"
    if "flag" in cond:
        return f"feature `{cond['flag']}` enabled"
    if "org" in cond:
        return f"organization setting `{cond['org']}` enabled"
    if "deployment" in cond:
        return f"{cond['deployment'].replace('_', '-')} deployment"
    if "scope" in cond:
        return f"the user has the `{cond['scope']}` permission"
    return f"`{cond.get('unknown', cond)}`"


def _matches_section(crumbs: str, section: str | None) -> bool:
    if not section:
        return True
    top = crumbs.split(CRUMB_SEPARATOR, 1)[0].lower()
    return top == section or (section in _SETTINGS_SECTION_ALIASES and top == "settings")


def visible_nav_links(
    features: Collection[str],
    scopes: Collection[str],
    section: str | None = None,
    include_sub_pages: bool | None = None,
) -> list[VisibleNavLink]:
    """Pages a user with `scopes` in an org with `features` can see, each with the condition
    left undecided.

    Pages whose condition depends on frontend code that can't be evaluated are left out.
    """
    features, scopes = frozenset(features), frozenset(scopes)
    section = section.lower() if section else None
    entries = _SNAPSHOT["entries"]
    candidates = [e for e in entries if _matches_section(e["crumbs"], section)]
    if not candidates:
        # An unrecognized section: fall back to every page, as if no section was given.
        section, candidates = None, entries
    # Sub-pages only for a section-scoped call by default: across every section they
    # make the list too long for Seer's tool output.
    sub_pages = include_sub_pages if include_sub_pages is not None else bool(section)
    candidates = [e for e in candidates if sub_pages or not e.get("sub_page")]

    visible: list[VisibleNavLink] = []
    seen: set[tuple[str, str]] = set()
    for entry in candidates:
        key = (entry["crumbs"], entry["path"])
        resolved = resolve_condition(entry.get("when"), features, scopes)
        if resolved is False or key in seen:
            continue
        pending = None if resolved is True else _without_unknowns(resolved)
        if resolved is not True and pending is None:
            continue
        seen.add(key)
        visible.append(VisibleNavLink(crumbs=entry["crumbs"], path=entry["path"], pending=pending))
    return visible
