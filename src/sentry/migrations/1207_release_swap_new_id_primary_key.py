import sentry.db.models.fields.bounded
import sentry.db.models.indexes
from django.db import migrations

from sentry.new_migrations.migrations import CheckedMigration
from sentry.new_migrations.monkey.special import SafeRunSQL

# Sequence-backed in production, identity anywhere built by running migrations; both end as an
# identity. Adding it after the rename is what puts the sequence where _reserve_ids looks.
# Foreign keys into sentry_release depend on the primary key index and pin the old column by
# position, so they are rebuilt against the new column; NOT VALID keeps each rebuild
# metadata-only, at the cost of leaving pre-existing rows unvalidated.
# Only US-1 has the hand-built (id, organization_id) index, so its drop is guarded; the new_id
# twin from 1196 exists everywhere and takes over the name in every region.
SWAP_SQL = """
DO $$
DECLARE
    id_sequence text;
    next_id bigint;
    pk_name text;
    fk record;
    fk_drop text;
    fk_add text;
    fk_drops text[] := '{}';
    fk_adds text[] := '{}';
BEGIN
    FOR fk IN
        SELECT
            conrelid::regclass AS table_name,
            conname AS constraint_name,
            pg_get_constraintdef(oid) AS definition,
            convalidated AS validated
        FROM pg_constraint
        WHERE contype = 'f' AND confrelid = 'sentry_release'::regclass
        ORDER BY conrelid::regclass::text
    LOOP
        -- Child tables first and sentry_release last: the order a child write takes them when
        -- its deferred FK check runs at commit, so the two cannot deadlock.
        EXECUTE format('LOCK TABLE %s IN ACCESS EXCLUSIVE MODE', fk.table_name);

        -- The primary key cannot be dropped while a foreign key still depends on it.
        fk_drop := format(
            'ALTER TABLE %s DROP CONSTRAINT %I', fk.table_name, fk.constraint_name
        );
        -- Queued rather than run, so every definition is read before the first drop.
        fk_drops := array_append(fk_drops, fk_drop);

        -- The same definition verbatim, which binds it to whichever column is named id then.
        fk_add := format(
            'ALTER TABLE %s ADD CONSTRAINT %I %s',
            fk.table_name, fk.constraint_name, fk.definition
        );
        -- Skips the scan of existing rows; new rows are still checked.
        IF fk.validated THEN
            fk_add := fk_add || ' NOT VALID';
        END IF;
        -- Queued for after the column rename, so sentry_release(id) is the wide column.
        fk_adds := array_append(fk_adds, fk_add);
    END LOOP;

    LOCK TABLE "sentry_release" IN ACCESS EXCLUSIVE MODE;

    id_sequence := pg_get_serial_sequence('sentry_release', 'id');
    IF id_sequence IS NULL THEN
        RAISE EXCEPTION 'sentry_release.id has no sequence to carry over';
    END IF;
    -- Any ALTER SEQUENCE blocks nextval until commit, so reserve_ids cannot claim an id
    -- between the snapshot and the drop; the sequence is dropped below regardless.
    EXECUTE format('ALTER SEQUENCE %s CACHE 1', id_sequence);
    EXECUTE format(
        'SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM %s', id_sequence
    ) INTO next_id;

    FOREACH fk_drop IN ARRAY fk_drops LOOP
        EXECUTE fk_drop;
    END LOOP;

    -- One of these two is how the old column got its values; the other is a no-op.
    ALTER TABLE "sentry_release" ALTER COLUMN "id" DROP IDENTITY IF EXISTS;
    ALTER TABLE "sentry_release" ALTER COLUMN "id" DROP DEFAULT;
    EXECUTE format('DROP SEQUENCE IF EXISTS %s', id_sequence);

    SELECT constraint_name INTO pk_name
    FROM information_schema.table_constraints
    WHERE table_schema = current_schema()
      AND table_name = 'sentry_release'
      AND constraint_type = 'PRIMARY KEY';

    EXECUTE format('ALTER TABLE "sentry_release" DROP CONSTRAINT %I', pk_name);

    -- Naming the constraint renames the prebuilt index onto it; inheriting would leave the
    -- key called after the unique index.
    ALTER TABLE "sentry_release" ADD CONSTRAINT "sentry_release_pkey"
        PRIMARY KEY USING INDEX "sentry_release_new_id_uniq";

    DROP INDEX IF EXISTS "sentry_release_id_organization_id";
    ALTER INDEX IF EXISTS "sentry_release_new_id_organization_id"
        RENAME TO "sentry_release_id_organization_id";

    -- Swap column names.
    ALTER TABLE "sentry_release" RENAME COLUMN "id" TO "id_tmp";
    ALTER TABLE "sentry_release" RENAME COLUMN "new_id" TO "id";
    ALTER TABLE "sentry_release" RENAME COLUMN "id_tmp" TO "new_id";

    EXECUTE format(
        'ALTER TABLE "sentry_release" ALTER COLUMN "id" '
        'ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next_id
    );

    FOREACH fk_add IN ARRAY fk_adds LOOP
        EXECUTE fk_add;
    END LOOP;
END $$;
"""

# Builds the unique index inside the lock, so this is not O(1) and would cross production's 10s
# statement timeout at scale. For tests and local work, not a production rollback plan.
# Fails if the sequence has passed 2^31, since the narrow column could not hold it.
UNSWAP_SQL = """
DO $$
DECLARE
    id_sequence text;
    next_id bigint;
    fk record;
    fk_drop text;
    fk_add text;
    fk_drops text[] := '{}';
    fk_adds text[] := '{}';
BEGIN
    FOR fk IN
        SELECT
            conrelid::regclass AS table_name,
            conname AS constraint_name,
            pg_get_constraintdef(oid) AS definition
        FROM pg_constraint
        WHERE contype = 'f' AND confrelid = 'sentry_release'::regclass
        ORDER BY conrelid::regclass::text
    LOOP
        EXECUTE format('LOCK TABLE %s IN ACCESS EXCLUSIVE MODE', fk.table_name);

        -- The primary key cannot be dropped while a foreign key still depends on it.
        fk_drop := format(
            'ALTER TABLE %s DROP CONSTRAINT %I', fk.table_name, fk.constraint_name
        );
        -- Queued rather than run, so every definition is read before the first drop.
        fk_drops := array_append(fk_drops, fk_drop);

        -- The same definition verbatim, which binds it to whichever column is named id then.
        fk_add := format(
            'ALTER TABLE %s ADD CONSTRAINT %I %s',
            fk.table_name, fk.constraint_name, fk.definition
        );
        -- Queued for after the column rename, so sentry_release(id) is the narrow column.
        fk_adds := array_append(fk_adds, fk_add);
    END LOOP;

    LOCK TABLE "sentry_release" IN ACCESS EXCLUSIVE MODE;

    id_sequence := pg_get_serial_sequence('sentry_release', 'id');
    EXECUTE format('ALTER SEQUENCE %s CACHE 1', id_sequence);
    EXECUTE format(
        'SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM %s', id_sequence
    ) INTO next_id;

    FOREACH fk_drop IN ARRAY fk_drops LOOP
        EXECUTE fk_drop;
    END LOOP;

    ALTER TABLE "sentry_release" ALTER COLUMN "id" DROP IDENTITY IF EXISTS;
    ALTER TABLE "sentry_release" ALTER COLUMN "id" DROP DEFAULT;
    EXECUTE format('DROP SEQUENCE IF EXISTS %s', id_sequence);

    ALTER TABLE "sentry_release" DROP CONSTRAINT "sentry_release_pkey";

    ALTER TABLE "sentry_release" RENAME COLUMN "new_id" TO "id_tmp";
    ALTER TABLE "sentry_release" RENAME COLUMN "id" TO "new_id";
    ALTER TABLE "sentry_release" RENAME COLUMN "id_tmp" TO "id";

    ALTER INDEX IF EXISTS "sentry_release_id_organization_id"
        RENAME TO "sentry_release_new_id_organization_id";

    CREATE UNIQUE INDEX "sentry_release_new_id_uniq" ON "sentry_release" ("new_id");

    ALTER TABLE "sentry_release" ADD CONSTRAINT "sentry_release_pkey" PRIMARY KEY ("id");
    EXECUTE format(
        'ALTER TABLE "sentry_release" ALTER COLUMN "id" '
        'ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next_id
    );

    FOREACH fk_add IN ARRAY fk_adds LOOP
        EXECUTE fk_add;
    END LOOP;
END $$;
"""


class Migration(CheckedMigration):
    # This flag is used to mark that a migration shouldn't be automatically run in production.
    # This should only be used for operations where it's safe to run the migration after your
    # code has deployed. So this should not be used for most operations that alter the schema
    # of a table.
    # Here are some things that make sense to mark as post deployment:
    # - Large data migrations. Typically we want these to be run manually so that they can be
    #   monitored and not block the deploy for a long period of time while they run.
    # - Adding indexes to large tables. Since this can take a long time, we'd generally prefer to
    #   run this outside deployments so that we don't block them. Note that while adding an index
    #   is a schema change, it's completely safe to run the operation after the code has deployed.
    # Once deployed, run these manually via: https://develop.sentry.dev/database-migrations/#migration-deployment

    is_post_deployment = True

    # The base class opts out of transactions for long-running backfills. This one is the
    # opposite: a short metadata-only rotation that leaves the table without a primary key if
    # it stops partway.
    atomic = True

    dependencies = [
        ("sentry", "1206_add_dashboard_create_scope"),
    ]

    operations = [
        migrations.SeparateDatabaseAndState(
            database_operations=[
                SafeRunSQL(
                    SWAP_SQL,
                    reverse_sql=UNSWAP_SQL,
                    hints={"tables": ["sentry_release"]},
                ),
            ],
            state_operations=[
                migrations.AlterField(
                    model_name="release",
                    name="new_id",
                    field=sentry.db.models.fields.bounded.BoundedIntegerField(),
                ),
                migrations.AddIndex(
                    model_name="release",
                    index=sentry.db.models.indexes.IndexWithPostgresNameLimits(
                        fields=["id", "organization"],
                        name="sentry_release_id_organization_id",
                    ),
                ),
            ],
        ),
    ]
