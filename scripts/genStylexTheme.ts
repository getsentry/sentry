for (const [prop, {css, values, expr}] of Object.entries(FIXED)) {
  for (const [value, cssValue] of Object.entries(values ?? {})) {
    fixedEntries.push(
      `${JSON.stringify(`${prop}:${value}`)}: {${css}: ${JSON.stringify(cssValue)}}`
    );
  }
  for (const [value, cssExpr] of Object.entries(expr ?? {})) {
    fixedEntries.push(`${JSON.stringify(`${prop}:${value}`)}: {${css}: ${cssExpr}}`);
  }
}

const layoutFile = `${HEADER}
import * as stylex from '@stylexjs/stylex';

import {border, background, shadow} from '@sentry/scraps/theme/tokens.stylex';
import {fontSize, lineHeight, radius, space} from '@sentry/scraps/theme/constants.stylex';

/**
 * One style per CSS property, reading its value from the inline custom
 * property \`--sx-\${property}\` (see \`layoutVarName\`).
 *
 * These are plain classes rather than StyleX dynamic styles: a dynamic style
 * compiles to a function and an \`@property\` rule per variable, which across
 * every property and breakpoint costs ~3x the JS and CSS.
 */
export const baseStyles = stylex.create({
${LAYOUT_PROPERTIES.map(p => `  ${p}: {${p}: 'var(--sx-${p})'},`).join('\n')}
});

/**
 * One style per CSS property and responsive key, keyed \`\${property}@\${key}\`,
 * reading \`--sx-\${property}-\${key}\`. Each applies only inside its breakpoint's
 * query, so several can be combined for one property.
 */
export const breakpointStyles = stylex.create({
${LAYOUT_PROPERTIES.flatMap(p =>
  BREAKPOINTS.map(
    ([key, query]) =>
      `  ${JSON.stringify(`${p}@${key}`)}: {${p}: {default: null, ${JSON.stringify(query)}: 'var(${layoutVarName(p, key)})'}},`
  )
).join('\n')}
});

/**
 * Static classes for common prop values, keyed \`\${prop}:\${value}\` with the
 * value as written at the call site, so they need no inline CSS variables.
 */
export const fixedStyles = stylex.create({
${fixedEntries.map(e => `  ${e},`).join('\n')}
});

/**
 * Variable name suffix per responsive key: StyleX orders \`@container\` rules by
 * their declaration text, so the suffix carries the breakpoint's position.
 */
export const breakpointVarSuffix: Record<string, string> = ${JSON.stringify(breakpointVarSuffix)};

export type LayoutProperty = keyof typeof baseStyles;
export type ResponsiveKey = ${BREAKPOINTS.map(([k]) => JSON.stringify(k)).join(' | ')};
`;

