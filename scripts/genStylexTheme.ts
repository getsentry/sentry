const tokensFile = `${HEADER}
import * as stylex from '@stylexjs/stylex';

${varGroups
  .map(
    ([name, light, _dark, doc]) =>
      `/** \`${doc}\`, as CSS variables. Light values; see darkTheme.tsx. */
export const ${name} = stylex.defineVars(${objectLiteral(flatten(light))});`
  )
  .join('\n\n')}
`;

const darkFile = `${HEADER}
import * as stylex from '@stylexjs/stylex';

import {${varGroups.map(([name]) => name).join(', ')}} from './tokens.stylex';

${varGroups
  .map(([name, light, dark]) => {
    const lightValues = flatten(light);
    const overrides = Object.fromEntries(
      Object.entries(flatten(dark)).filter(([k, v]) => lightValues[k] !== v)
    );
    return `const ${name}Dark = stylex.createTheme(${name}, ${objectLiteral(overrides)});`;
  })
  .join('\n\n')}

/**
 * Applied to the document root when the dark theme is active.
 */
export const stylexDarkTheme = [${varGroups.map(([name]) => `${name}Dark`).join(', ')}];
`;

