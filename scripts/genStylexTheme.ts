/**
 * Generates the StyleX theme and layout style modules for @sentry/scraps from
 * the JS theme, so StyleX components and Emotion components read the same
 * values.
 *
 * - theme/tokens.stylex.ts      defineVars: light values of theme-dependent tokens
 * - theme/constants.stylex.ts   defineConsts: theme-independent scales
 * - theme/darkTheme.tsx         createTheme: dark overrides of tokens.stylex.ts
 * - layout/generatedStyles.tsx  stylex.create: per-property layout styles
 *
 * Usage:
 *   pnpm gen:stylex-theme
 */
