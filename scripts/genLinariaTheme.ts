const propertyName = (name: string) =>
  name.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase());
const tag = (text: string) => 'css\u0060\n' + text + '\n\u0060';
const resolveExpression = (expression: string): string => {
  if (expression === "'auto'") {
    return 'auto';
  }
  const [group, key] = expression.replace(/\["([^"]+)"\]/, '.$1').split('.');
  if (!group || !key) {
    throw new Error(`Invalid theme expression: ${expression}`);
  }
  const constants = constGroups[group];
  if (constants) {
    return String(constants[key]);
  }
  const values = flatten(varGroups.find(([name]) => name === group)![1]);
  return 'var(' + variable(group, key) + ', ' + values[key] + ')';
};
const fixedEntries: string[] = [
  'border',
  'borderTop',
  'borderBottom',
  'borderLeft',
  'borderRight',
].flatMap(side => [
  JSON.stringify(side + ':none') +
    ': ' +
    tag(propertyName(side) + '-width: 0;\n' + propertyName(side) + '-style: none;'),
  ...Object.entries(BORDER_COLORS).map(
    ([variant, color]) =>
      JSON.stringify(side + ':' + variant) +
      ': ' +
      tag(
        propertyName(side) +
          '-width: 1px;\n' +
          propertyName(side) +
          '-style: solid;\n' +
          propertyName(side) +
          '-color: ' +
          resolveExpression(color) +
          ';'
      )
  ),
]);
for (const [prop, {css, values, expr}] of Object.entries(FIXED)) {
  for (const [value, cssValue] of Object.entries(values ?? {})) {
    fixedEntries.push(
      JSON.stringify(prop + ':' + value) +
        ': ' +
        tag(propertyName(css) + ': ' + cssValue + ';')
    );
  }
  for (const [value, cssExpr] of Object.entries(expr ?? {})) {
    fixedEntries.push(
      JSON.stringify(prop + ':' + value) +
        ': ' +
        tag(propertyName(css) + ': ' + resolveExpression(cssExpr) + ';')
    );
  }
}
