type Tree = Record<string, unknown>;

/** `['chonky', 'embossed', 'accent']` → `chonkyEmbossedAccent` */
function camelJoin(segments: string[]): string {
  return segments
    .map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1)))
    .join('');
}

/** Flattens a nested token tree into `{camelCasedPath: value}`, skipping non-CSS values. */
function flatten(tree: Tree, prefix: string[] = []): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [key, value] of Object.entries(tree)) {
    if (Array.isArray(value) || typeof value === 'function') {
      continue;
    }
    if (value && typeof value === 'object') {
      Object.assign(result, flatten(value as Tree, [...prefix, key]));
      continue;
    }
    result[camelJoin([...prefix, key])] = String(value);
  }
  return result;
}

function objectLiteral(values: Record<string, string | number>): string {
  return `{${Object.entries(values)
    .map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(',\n')}}`;
}

