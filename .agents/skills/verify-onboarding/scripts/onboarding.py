#!/usr/bin/env python
"""Launch, check, seed, inspect, and stop a disposable Sentry devserver for onboarding verification.

Run with the repo virtualenv from the sentry checkout root:

    .venv/bin/python .agents/skills/verify-onboarding/scripts/onboarding.py <command>

Commands: launch, doctor, seed, login, state, event, stop. See ../SKILL.md.
"""

from __future__ import annotations

import argparse
import json  # noqa: S003  # stdlib on purpose: launch, doctor, and stop run before Django is set up
import os
import re
import secrets
import shutil
import signal
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any, NoReturn

REPO = Path(__file__).resolve().parents[4]
RUN_DIR = Path(os.environ.get("VERIFY_ONBOARDING_DIR", "/tmp/verify-onboarding"))
RUN_FILE = RUN_DIR / "run.json"
CONF_DIR = RUN_DIR / "conf"
LOG_FILE = RUN_DIR / "devserver.log"
BASE_CONF = Path(os.environ.get("VERIFY_ONBOARDING_BASE_CONF", "~/.sentry")).expanduser()
EVIDENCE_ROOT = REPO / ".artifacts" / "verify-onboarding"
HOST = "127.0.0.1"
PORT = 8000
BASE_URL = f"http://dev.getsentry.net:{PORT}"
SENTRY_BIN = REPO / ".venv" / "bin" / "sentry"

# A fixed client id lets the settings overlay name the handoff application before it exists.
HANDOFF_CLIENT_ID = "verify-onboarding-agent-cli"

FLAGS = {
    "agentic": "organizations:onboarding-agentic-setup",
    "messaging": "organizations:onboarding-scm-messaging-experiment",
    "scm-project-creation": "organizations:onboarding-scm-project-creation",
    "scm": "organizations:onboarding-scm",
}
DEFAULT_FLAGS = "agentic,scm-project-creation"
# SaaS plans grant these. Without them the onboarding product toggles render disabled.
PRODUCT_FEATURES = (
    "organizations:session-replay",
    "organizations:ourlogs-enabled",
    "organizations:tracemetrics-enabled",
)

OVERLAY = """\
# Generated by verify-onboarding. Removed by `onboarding.py stop`.
import os as _os

_base = {base!r}
exec(compile(open(_os.path.join(_base, "sentry.conf.py")).read(), _os.path.join(_base, "sentry.conf.py"), "exec"))

SENTRY_FEATURES.update({features!r})
# Relay is the only ingest path, and the devserver starts the ingest consumers only when this is on.
SENTRY_USE_RELAY = {ingest!r}
SENTRY_OPTIONS.update(
    {{
        "onboarding.agent-handoff.client-id": {client_id!r},
        "oauth.setup-code.allowed-client-ids": [{client_id!r}],
    }}
)
"""


def emit(text: str, *, err: bool = False) -> None:
    (sys.stderr if err else sys.stdout).write(text + "\n")


def fail(message: str) -> NoReturn:
    emit(f"verify-onboarding: {message}", err=True)
    sys.exit(1)


def read_run() -> dict[str, Any]:
    if not RUN_FILE.exists():
        fail(f"no run state at {RUN_FILE}; run `launch` first")
    return json.loads(RUN_FILE.read_text())


def http_status(url: str, timeout: float = 10) -> int | None:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            return response.status
    except urllib.error.HTTPError as error:
        return error.code
    except (urllib.error.URLError, TimeoutError, ConnectionError):
        return None


def listening_pids(port: int) -> set[int]:
    """PIDs that own a listening TCP socket on `port` (lsof on macOS, /proc on Linux)."""
    if shutil.which("lsof"):
        result = subprocess.run(
            ["lsof", "-nP", f"-iTCP:{port}", "-sTCP:LISTEN", "-t"],
            capture_output=True,
            text=True,
            check=False,
        )
        return {int(pid) for pid in result.stdout.split()}

    inodes = set()
    for table in ("/proc/net/tcp", "/proc/net/tcp6"):
        if not os.path.exists(table):
            continue
        for line in Path(table).read_text().splitlines()[1:]:
            fields = line.split()
            local_port = int(fields[1].rsplit(":", 1)[1], 16)
            if local_port == port and fields[3] == "0A":
                inodes.add(fields[9])
    pids = set()
    for proc in Path("/proc").iterdir():
        if not proc.name.isdigit():
            continue
        try:
            for fd in (proc / "fd").iterdir():
                target = os.readlink(fd)
                if target.startswith("socket:[") and target[8:-1] in inodes:
                    pids.add(int(proc.name))
                    break
        except OSError:
            continue
    return pids


def descendants(root: int) -> set[int]:
    """`root` and every process below it. rsbuild starts its own session, so a process group misses it."""
    listing = subprocess.run(
        ["ps", "-A", "-o", "pid=,ppid="], capture_output=True, text=True, check=True
    )
    children: dict[int, list[int]] = {}
    for line in listing.stdout.splitlines():
        pid, ppid = (int(value) for value in line.split())
        children.setdefault(ppid, []).append(pid)
    found, pending = set(), [root]
    while pending:
        pid = pending.pop()
        if pid not in found:
            found.add(pid)
            pending.extend(children.get(pid, []))
    return found


def git_rev() -> str:
    return subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True, check=True
    ).stdout.strip()


def pid_exists(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    return True


def alive(run: dict[str, Any]) -> bool:
    """The recorded devserver still runs, and the PID was not reused by another process."""
    try:
        return os.getpgid(run["pid"]) == run["pgid"]
    except ProcessLookupError:
        return False


def launch(args: argparse.Namespace) -> None:
    if RUN_FILE.exists():
        fail(f"{RUN_FILE} exists; run `stop` before launching again")
    if listening_pids(PORT) or http_status(f"http://{HOST}:{PORT}/", timeout=3) is not None:
        fail(
            f"port {PORT} is already in use by a server this run did not start; refusing to drive it"
        )
    unknown = [name for name in args.flags.split(",") if name and name not in FLAGS]
    if unknown:
        fail(f"unknown flags {unknown}; known: {sorted(FLAGS)}")
    enabled = {FLAGS[name] for name in args.flags.split(",") if name}
    features = {feature: feature in enabled for feature in FLAGS.values()}
    features.update(dict.fromkeys(PRODUCT_FEATURES, True))

    run_id = args.run_id or time.strftime("%Y%m%d-%H%M%S")
    CONF_DIR.mkdir(parents=True, exist_ok=True)
    (CONF_DIR / "sentry.conf.py").write_text(
        OVERLAY.format(
            base=str(BASE_CONF), features=features, ingest=args.ingest, client_id=HANDOFF_CLIENT_ID
        )
    )
    config_yml = CONF_DIR / "config.yml"
    if not config_yml.exists():
        config_yml.symlink_to(BASE_CONF / "config.yml")

    env = {
        **os.environ,
        "SENTRY_CONF": str(CONF_DIR),
        "PATH": f"{REPO / '.venv' / 'bin'}:{os.environ['PATH']}",
    }
    command = [str(SENTRY_BIN), "devserver", "--no-reload", "--no-prefix"]
    command += ["--workers", "--ingest", "--dev-consumer"] if args.ingest else ["--no-workers"]
    command.append(f"{HOST}:{PORT}")
    with LOG_FILE.open("w") as log:
        process = subprocess.Popen(
            command,
            cwd=REPO,
            env=env,
            stdout=log,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    run = {
        "run_id": run_id,
        "pid": process.pid,
        "pgid": os.getpgid(process.pid),
        "flags": sorted(name for name, feature in FLAGS.items() if feature in enabled),
        "ingest": args.ingest,
        "conf_dir": str(CONF_DIR),
        "git_rev": git_rev(),
        "base_url": BASE_URL,
        "evidence_dir": str(EVIDENCE_ROOT / run_id),
    }
    RUN_FILE.write_text(json.dumps(run, indent=2))
    Path(run["evidence_dir"]).mkdir(parents=True, exist_ok=True)

    deadline = time.monotonic() + args.timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            emit(LOG_FILE.read_text()[-4000:], err=True)
            fail(f"devserver exited with {process.returncode}; log at {LOG_FILE}")
        built = re.search(r"built in .* \(app\)", LOG_FILE.read_text())
        if built and http_status(f"{BASE_URL}/auth/login/", timeout=30) == 200:
            emit(json.dumps(run, indent=2))
            return
        time.sleep(2)
    fail(f"devserver not ready after {args.timeout}s; log at {LOG_FILE}. Run `stop`.")


def doctor(args: argparse.Namespace) -> None:
    run = read_run()
    checks: list[tuple[str, bool, str]] = []
    checks.append(("devserver process alive", alive(run), f"pid {run['pid']}"))

    owners = listening_pids(PORT)
    owned = bool(owners) and owners <= descendants(run["pid"])
    checks.append((f"port {PORT} owned by this run", owned, f"listeners {sorted(owners)}"))

    checks.append(("checkout revision unchanged", git_rev() == run["git_rev"], run["git_rev"][:12]))
    status = http_status(f"{BASE_URL}/api/client-config/")
    checks.append(("client-config answers", status == 200, f"HTTP {status}"))
    preview = http_status(f"{BASE_URL}/agent-handoff.md?preview=1&flow=onboarding")
    checks.append(("agent handoff guide answers", preview == 200, f"HTTP {preview}"))

    for name, ok, detail in checks:
        emit(f"{'ok ' if ok else 'BAD'} {name} ({detail})")
    emit(f"flags: {', '.join(run['flags']) or 'none'}; ingest: {run['ingest']}")
    emit(f"evidence: {run['evidence_dir']}")
    if not all(ok for _, ok, _ in checks):
        sys.exit(1)


def configure_django() -> None:
    os.environ["SENTRY_CONF"] = str(CONF_DIR)
    from sentry.runner import configure

    configure()


def seed(args: argparse.Namespace) -> None:
    run = read_run()
    configure_django()
    from sentry.models.apiapplication import ApiApplication
    from sentry.testutils.factories import Factories  # noqa: S007  # seeds a local devserver only
    from sentry.users.models.user import User

    application, _ = ApiApplication.objects.get_or_create(
        client_id=HANDOFF_CLIENT_ID,
        defaults={"name": "Verify onboarding agent CLI", "client_secret": None, "owner_id": None},
    )
    if application.client_secret is not None:
        application.update(client_secret=None)

    suffix = run["run_id"].replace("-", "")[-10:] + secrets.token_hex(2)
    password = f"verify-{secrets.token_hex(8)}"

    def user(role: str) -> User:
        created = Factories.create_user(
            email=f"verify-{role}-{suffix}@example.com", is_superuser=False
        )
        created.set_password(password)
        created.save()
        return created

    owner, member = user("owner"), user("member")
    # One fresh org per journey: each journey creates projects, and onboarding keys off the org's state.
    new_orgs = []
    for index in range(1, args.new_orgs + 1):
        org = Factories.create_organization(
            name=f"Verify New {suffix} {index}", slug=f"verify-new-{suffix}-{index}", owner=None
        )
        Factories.create_member(user=owner, organization=org, role="owner")
        Factories.create_member(user=member, organization=org, role="member")
        Factories.create_team(
            organization=org, name="Onboarding", slug="onboarding", members=[owner, member]
        )
        new_orgs.append(org.slug)

    existing_org = Factories.create_organization(
        name=f"Verify Existing {suffix}", slug=f"verify-existing-{suffix}", owner=None
    )
    Factories.create_member(user=owner, organization=existing_org, role="owner")
    Factories.create_member(user=member, organization=existing_org, role="member")
    existing_team = Factories.create_team(
        organization=existing_org, name="Backend", members=[owner, member]
    )
    Factories.create_project(
        organization=existing_org,
        teams=[existing_team],
        name="api-server",
        slug="api-server",
        platform="python",
    )

    seeded = {
        "password": password,
        "owner_email": owner.email,
        "member_email": member.email,
        "new_orgs": new_orgs,
        "new_team": "onboarding",
        "existing_org": existing_org.slug,
        "existing_team": existing_team.slug,
        "handoff_client_id": application.client_id,
    }
    out = RUN_DIR / "seed.json"
    out.write_text(json.dumps(seeded, indent=2))
    emit(json.dumps(seeded, indent=2))


def state(args: argparse.Namespace) -> None:
    configure_django()
    from sentry.models.organization import Organization
    from sentry.models.project import Project
    from sentry.models.projectkey import ProjectKey

    organization = Organization.objects.get(slug=args.org)
    projects = []
    for project in Project.objects.filter(organization=organization).order_by("id"):
        projects.append(
            {
                "id": project.id,
                "slug": project.slug,
                "platform": project.platform,
                "status": project.get_status_display(),
                "first_event": project.first_event.isoformat() if project.first_event else None,
                "dsns": [key.dsn_public for key in ProjectKey.objects.filter(project=project)],
            }
        )
    result = {"org": organization.slug, "projects": projects}
    text = json.dumps(result, indent=2)
    emit(text)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text + "\n")


def event(args: argparse.Namespace) -> None:
    """Send one error through Relay with the project's public DSN, as an instrumented app would."""
    configure_django()
    from sentry.models.projectkey import ProjectKey

    key = ProjectKey.objects.filter(
        project__organization__slug=args.org, project__slug=args.project
    ).first()
    if key is None:
        fail(f"no DSN for {args.org}/{args.project}")
    payload = json.dumps(
        {
            "event_id": secrets.token_hex(16),
            "platform": "javascript",
            "level": "error",
            "exception": {"values": [{"type": "Error", "value": args.message}]},
        }
    ).encode()
    request = urllib.request.Request(
        f"{BASE_URL}/api/{key.project_id}/store/",
        data=payload,
        headers={
            "Content-Type": "application/json",
            "X-Sentry-Auth": f"Sentry sentry_version=7, sentry_client=verify-onboarding/1.0, sentry_key={key.public_key}",
        },
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        emit(f"HTTP {response.status} {response.read().decode()}")


def browser(session: str, *command: str) -> str:
    try:
        result = subprocess.run(
            ["agent-browser", "--session", session, *command],
            capture_output=True,
            text=True,
            check=False,
            timeout=90,
        )
    except subprocess.TimeoutExpired:
        fail(f"agent-browser {' '.join(command)} timed out")
    if result.returncode != 0:
        fail(f"agent-browser {' '.join(command)} failed: {result.stderr.strip()}")
    return result.stdout


def login(args: argparse.Namespace) -> None:
    """Open a browser session and sign in through the real login form as a seeded user."""
    seeded = json.loads((RUN_DIR / "seed.json").read_text())
    session = args.session or f"verify-onboarding-{args.role}"
    subprocess.run(
        ["agent-browser", "--session", session, "close"],
        capture_output=True,
        check=False,
        timeout=60,
    )
    # Clipboard writes need a secure context. Production is HTTPS; the devserver is plain HTTP.
    browser(
        session,
        "--args",
        f"--unsafely-treat-insecure-origin-as-secure={BASE_URL}",
        "open",
        f"{BASE_URL}/auth/login/",
    )
    browser(session, "wait", 'input[name="email"]')
    browser(session, "find", "label", "Email", "fill", seeded[f"{args.role}_email"])
    browser(session, "find", "label", "Password", "fill", seeded["password"])
    browser(session, "find", "role", "button", "click", "--name", "Log in to Sentry")
    browser(session, "wait", "--load", "networkidle")
    url = browser(session, "get", "url").strip()
    if "/auth/login/" in url:
        fail(f"login as {args.role} did not leave the login page ({url})")
    emit(f"session {session} signed in as {seeded[f'{args.role}_email']} at {url}")


def stop(args: argparse.Namespace) -> None:
    if not RUN_FILE.exists():
        emit("nothing to stop")
        return
    run = json.loads(RUN_FILE.read_text())
    pids = descendants(run["pid"]) if alive(run) else set()
    for sig in (signal.SIGTERM, signal.SIGKILL):
        for pid in pids:
            try:
                os.kill(pid, sig)
            except ProcessLookupError:
                pass
        for _ in range(30):
            pids = {pid for pid in pids if pid_exists(pid)}
            if not pids:
                break
            time.sleep(1)
    shutil.rmtree(CONF_DIR, ignore_errors=True)
    for path in (RUN_FILE, RUN_DIR / "seed.json"):
        path.unlink(missing_ok=True)
    emit(f"stopped devserver {run['pid']} and its children; evidence kept at {run['evidence_dir']}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    commands = parser.add_subparsers(dest="command", required=True)

    launch_parser = commands.add_parser(
        "launch", help="start a devserver with an onboarding flag profile"
    )
    launch_parser.add_argument(
        "--flags", default=DEFAULT_FLAGS, help=f"comma list of {sorted(FLAGS)}"
    )
    launch_parser.add_argument(
        "--no-ingest", dest="ingest", action="store_false", help="skip workers and event ingest"
    )
    launch_parser.add_argument("--run-id", default=None)
    launch_parser.add_argument("--timeout", type=int, default=420)
    launch_parser.set_defaults(func=launch)

    commands.add_parser(
        "doctor", help="read-only check that this run owns a healthy instance"
    ).set_defaults(func=doctor)
    seed_parser = commands.add_parser(
        "seed", help="create users, orgs, and the agent handoff application"
    )
    seed_parser.add_argument(
        "--new-orgs", type=int, default=6, help="fresh orgs to create, one per journey"
    )
    seed_parser.set_defaults(func=seed)

    state_parser = commands.add_parser(
        "state", help="print projects and DSNs of an org (read-only)"
    )
    state_parser.add_argument("org")
    state_parser.add_argument("--out", default=None)
    state_parser.set_defaults(func=state)

    event_parser = commands.add_parser("event", help="send an error to a project through its DSN")
    event_parser.add_argument("org")
    event_parser.add_argument("project")
    event_parser.add_argument("--message", default="verify-onboarding manual test error")
    event_parser.set_defaults(func=event)

    login_parser = commands.add_parser("login", help="sign a browser session in as a seeded user")
    login_parser.add_argument("role", choices=["owner", "member"])
    login_parser.add_argument(
        "--session", default=None, help="agent-browser session (default verify-onboarding-<role>)"
    )
    login_parser.set_defaults(func=login)

    commands.add_parser("stop", help="stop the devserver this run started").set_defaults(func=stop)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
